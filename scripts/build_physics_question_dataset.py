def main() -> None:
    catalog = json.loads((ROOT / "config" / "books.json").read_text(encoding="utf-8"))
    book = next(item for item in catalog if item["id"] == "physics-9-10")
    chapters = {int(item["id"]): item for item in book["chapters"]}
    assert set(QUESTIONS) == set(range(1, 14))
    rows = []
    for chapter_id, chapter_questions in QUESTIONS.items():
        assert len(chapter_questions) == 18, (chapter_id, len(chapter_questions))
        chapter = chapters[chapter_id]
        for offset, question in enumerate(chapter_questions, start=1):
            rows.append({
                "id": f"physics-{chapter_id:02d}-{offset:02d}", "question": question,
                "label": chapter_id - 1, "chapter_id": chapter_id,
                "chapter_title": chapter["title_bn"],
                "chapter_page_range": [chapter["page_start"], chapter["page_end"]],
            })
    assert len(rows) == 234
    assert len({row["question"] for row in rows}) == 234
    document = {
        "version": "1.0", "language": "bn", "task": "physics-chapter-classification",
        "source": book["markdown_path"], "count": len(rows), "label_count": 13,
        "questions_per_chapter": 18, "questions": rows,
    }
    OUTPUT.write_text(json.dumps(document, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Wrote {len(rows)} curated questions to {OUTPUT}")


if __name__ == "__main__":
    main()
